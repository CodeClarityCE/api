import { ApiProperty } from "@nestjs/swagger";
import { Expose } from "class-transformer";
import { Column, Entity, Index, PrimaryGeneratedColumn } from "typeorm";

import { timestampAsIso } from "../timestamp-column";

@Entity("friends_of_php")
export class FriendsOfPhp {
  @PrimaryGeneratedColumn("uuid")
  @ApiProperty()
  @Expose()
  id!: string;

  @Column()
  @Index({ unique: true })
  @ApiProperty()
  @Expose()
  advisory_id!: string;

  @Column()
  @ApiProperty()
  @Expose()
  title!: string;

  @Column({ nullable: true })
  @ApiProperty()
  @Expose()
  cve!: string;

  @Column()
  @ApiProperty()
  @Expose()
  link!: string;

  @Column()
  @ApiProperty()
  @Expose()
  reference!: string;

  @Column({ nullable: true })
  @ApiProperty()
  @Expose()
  composer!: string;

  @Column("text", { nullable: true })
  @ApiProperty()
  @Expose()
  description!: string;

  @Column("jsonb", { default: {} })
  @ApiProperty()
  @Expose()
  branches!: unknown;

  @Column({ type: "timestamptz", nullable: true, transformer: timestampAsIso })
  @ApiProperty()
  @Expose()
  published!: string;

  @Column({ type: "timestamptz", nullable: true, transformer: timestampAsIso })
  @ApiProperty()
  @Expose()
  modified!: string;

  @Column({ type: "varchar", nullable: true })
  @ApiProperty()
  @Expose()
  retired_reason?: string | null;

  @Column({ type: "timestamptz", nullable: true, transformer: timestampAsIso })
  @ApiProperty()
  @Expose()
  retired_at?: string | null;

  // Upstream authority this record derives from, generated by the database.
  @Column({ type: "varchar", insert: false, update: false, nullable: true })
  @ApiProperty()
  @Expose()
  origin?: string;
}
