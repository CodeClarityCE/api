import { ApiProperty } from "@nestjs/swagger";
import { Expose } from "class-transformer";
import { Column, Entity, Index, PrimaryGeneratedColumn } from "typeorm";

import { timestampAsIso } from "../timestamp-column";

export const AdvisoryKind = {
  Vulnerability: "vulnerability",
  Malicious: "malicious",
} as const;
export type AdvisoryKind = (typeof AdvisoryKind)[keyof typeof AdvisoryKind];

@Entity("osv")
export class OSV {
  @PrimaryGeneratedColumn("uuid")
  @ApiProperty()
  @Expose()
  id!: string;

  @Column()
  @Index({ unique: true })
  @ApiProperty()
  @Expose()
  osv_id!: string;

  @Column({ nullable: true })
  @ApiProperty()
  @Expose()
  schema_version!: string;

  @Column({ nullable: true })
  @ApiProperty()
  @Expose()
  vlai_score!: string;

  @Column("float", { nullable: true })
  @ApiProperty()
  @Expose()
  vlai_confidence!: number;

  @Column({ type: "timestamptz", nullable: true, transformer: timestampAsIso })
  @ApiProperty()
  @Expose()
  modified!: string;

  @Column({ type: "timestamptz", nullable: true, transformer: timestampAsIso })
  @ApiProperty()
  @Expose()
  published!: string;

  @Column({ type: "timestamptz", nullable: true, transformer: timestampAsIso })
  @ApiProperty()
  @Expose()
  withdrawn!: string;

  @Column({ nullable: true })
  @ApiProperty()
  @Expose()
  summary!: string;

  @Column({ nullable: true })
  @ApiProperty()
  @Expose()
  details!: string;

  @Column({ nullable: true })
  @ApiProperty()
  @Expose()
  cve!: string;

  @Column("jsonb", { nullable: true })
  @ApiProperty()
  @Expose()
  aliases!: unknown;

  @Column("jsonb", { nullable: true })
  @ApiProperty()
  @Expose()
  related!: unknown;

  @Column("jsonb", { nullable: true })
  @ApiProperty()
  @Expose()
  severity!: unknown;

  @Column("jsonb", { nullable: true })
  @ApiProperty()
  @Expose()
  affected!: unknown;

  @Column("jsonb", { nullable: true })
  @ApiProperty()
  @Expose()
  references!: unknown;

  @Column("jsonb", { nullable: true })
  @ApiProperty()
  @Expose()
  credits!: unknown;

  @Column("jsonb", { nullable: true })
  @ApiProperty()
  @Expose()
  database_specific!: unknown;

  @Column("jsonb", { nullable: true })
  @ApiProperty()
  @Expose()
  cwes!: unknown;

  @Column({ type: "varchar", default: AdvisoryKind.Vulnerability })
  @ApiProperty()
  @Expose()
  kind?: AdvisoryKind;

  @Column({ type: "jsonb", insert: false, update: false, nullable: true })
  @ApiProperty()
  @Expose()
  cve_aliases?: string[];

  @Column({ type: "varchar", nullable: true })
  @ApiProperty()
  @Expose()
  retired_reason?: string | null;

  @Column({ type: "timestamptz", nullable: true, transformer: timestampAsIso })
  @ApiProperty()
  @Expose()
  retired_at?: string | null;

  // Upstream authority this record derives from, generated by the database.
  @Column({ type: "varchar", insert: false, update: false, nullable: true })
  @ApiProperty()
  @Expose()
  origin?: string;
}
