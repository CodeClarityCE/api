import { ApiProperty } from "@nestjs/swagger";
import { Expose } from "class-transformer";
import { Column, Entity, Index, PrimaryGeneratedColumn } from "typeorm";

import { timestampAsIso } from "../timestamp-column";

@Entity("nvd")
export class NVD {
  @PrimaryGeneratedColumn("uuid")
  @ApiProperty()
  @Expose()
  id!: string;

  @Column()
  @Index({ unique: true })
  @ApiProperty()
  @Expose()
  nvd_id!: string;

  @Column({ nullable: true })
  @ApiProperty()
  @Expose()
  sourceIdentifier!: string;

  @Column({ type: "timestamptz", nullable: true, transformer: timestampAsIso })
  @ApiProperty()
  @Expose()
  published!: string;

  @Column({ type: "timestamptz", nullable: true, transformer: timestampAsIso })
  @ApiProperty()
  @Expose()
  lastModified!: string;

  @Column({ nullable: true })
  @ApiProperty()
  @Expose()
  vulnStatus!: string;

  @Column("jsonb", { nullable: true })
  @ApiProperty()
  @Expose()
  descriptions!: unknown;

  @Column({ nullable: true })
  @ApiProperty()
  @Expose()
  vlai_score!: string;

  @Column("float", { nullable: true })
  @ApiProperty()
  @Expose()
  vlai_confidence!: number;

  @Column("jsonb", { nullable: true })
  @ApiProperty()
  @Expose()
  metrics!: unknown;

  @Column("jsonb", { nullable: true })
  @ApiProperty()
  @Expose()
  weaknesses!: unknown;

  @Column("jsonb", { nullable: true })
  @ApiProperty()
  @Expose()
  configurations!: unknown;

  @Column("jsonb", { nullable: true })
  @ApiProperty()
  @Expose()
  affectedFlattened!: unknown;

  @Column("jsonb", { nullable: true })
  @ApiProperty()
  @Expose()
  affected!: unknown;

  @Column("jsonb", { nullable: true })
  @ApiProperty()
  @Expose()
  references!: unknown;

  @Column({ type: "varchar", nullable: true })
  @ApiProperty()
  @Expose()
  retired_reason?: string | null;

  @Column({ type: "timestamptz", nullable: true, transformer: timestampAsIso })
  @ApiProperty()
  @Expose()
  retired_at?: string | null;

  // Upstream authority this record derives from, generated by the database.
  @Column({ type: "varchar", insert: false, update: false, nullable: true })
  @ApiProperty()
  @Expose()
  origin?: string;
}
